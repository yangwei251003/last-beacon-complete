import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const root = fileURLToPath(new URL('..', import.meta.url));
test('offline build is standalone, executable and retains original MIT license', async () => {
  execFileSync(process.execPath, ['build.mjs'], { cwd: root, stdio: 'pipe', timeout: 30000 });
  const html = await readFile(new URL('../dist/last-beacon.html', import.meta.url), 'utf8');
  assert.ok(html.includes('Copyright (c) 2026 stackloomdev'));
  assert.ok(html.includes('Permission is hereby granted, free of charge'));
  assert.ok(html.includes('余烬'));
  assert.doesNotMatch(html, /<script\b[^>]*\bsrc\s*=/i);
  assert.doesNotMatch(html, /<link\b[^>]*rel=["']stylesheet/i);
  assert.doesNotMatch(html, /<(?:img|audio|video|iframe)\b[^>]*src=["']https?:/i);
  assert.doesNotMatch(html, /(?:fetch\s*\(\s*['"]https?:|new\s+WebSocket\s*\()/);
  assert.doesNotMatch(html, /@import\s|url\(\s*['"]?https?:/i);
  const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
  assert.ok(script, 'inline runtime exists');
  assert.doesNotThrow(() => new vm.Script(script), 'bundled JavaScript parses');
  const license = await readFile(new URL('../dist/LICENSE', import.meta.url), 'utf8');
  assert.ok(license.includes('Copyright (c) 2026 stackloomdev'));
  const manifest = JSON.parse(await readFile(new URL('../dist/BUILD-MANIFEST.json', import.meta.url), 'utf8'));
  assert.ok(manifest.modules.includes('src/app.js'));
  assert.ok(manifest.modules.includes('src/power.js'));
  assert.ok(manifest.sourceFiles.every(item => !item.path.includes('/3d/') && item.path !== 'src/style.css'));
  const sources = await readdir(new URL('../dist/source/src/', import.meta.url));
  assert.deepEqual(sources.sort(), [...manifest.modules.map(p => p.slice(4)), 'ui.css'].sort());
});
